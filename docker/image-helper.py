"""Docker builder for QGIS images.


image-helper.py <version> [options]

options:
    -arm      - build for arm64 (default amd64)
    -debug    - build the debug image
    -latest   - tag the image with the major version (e.g. "3.34")

"""

import argparse
import os
import shutil
import subprocess
import sys

# see /make.sh

BASE_DIR = os.path.abspath(os.path.dirname(__file__) + '/..')
BUILD_DIR = '/opt/gbd/gbd-qgis-server-build'

# QGIS major version -> ubuntu version, should be the same as in the compile dockerfile
UBUNTU_VERSIONS = {
    '3': '24.04',
    '4': '26.04',
}


class Builder:
    vendor = 'gbdconsult'

    def __init__(self, args):
        self.build_dir = BUILD_DIR + '/out'

        self.args = args

        self.mode = 'debug' if args.debug else 'release'

        v = args.version.split('.')
        if len(v) != 3 or any(not s.isdigit() for s in v):
            sys.exit('<version> must be xx.yy.zz')
        self.version = v[0] + '.' + v[1] + '.' + v[2]
        self.version_major = v[0] + '.' + v[1]

        self.qgis_major = v[0]
        if self.qgis_major not in UBUNTU_VERSIONS:
            sys.exit(f'unsupported QGIS major version: {self.qgis_major}')
        self.ubuntu_version = UBUNTU_VERSIONS[self.qgis_major]

        self.arch = 'arm64' if args.arm else 'amd64'

        self.image_name = f'{self.vendor}/gbd-qgis-server-{self.arch}'
        if self.mode == 'debug':
            self.image_name += '-debug'
        self.image_full_name = f'{self.image_name}:{self.version}'

        self.image_description = f'QGIS Server {self.version}'

        self.dockerfile_name = 'Dockerfile'

        # resources from the NorBit alkis plugin
        self.alkisplugin_package = 'alkisplugin'

        # our compiled qgis package (see /make.sh compile-in-container)
        self.qgis_package = f'compiled-qgis-server-{self.version}-{self.arch}-{self.mode}'

    def main(self):
        self.prepare()

        run(f'cd {self.build_dir} && docker build --progress plain --pull --no-cache -f {self.dockerfile_name} -t {self.image_full_name} .')

        if self.args.latest:
            run(f'docker tag {self.image_full_name} {self.image_name}:{self.version_major}')

    def prepare(self):
        os.chdir(self.build_dir)

        if not os.path.isdir(f'{self.qgis_package}'):
            sys.exit(f'not found: {self.build_dir}/{self.qgis_package}')

        self.apt_list = []
        for path in [f'{BASE_DIR}/docker/apt-{self.qgis_major}.lst', f'{self.qgis_package}/shlibdeps.lst']:
            for s in lines(read_file(path)):
                if s not in self.apt_list:
                    self.apt_list.append(s)

        shutil.rmtree(self.alkisplugin_package, ignore_errors=True)
        shutil.copytree(f'{BASE_DIR}/docker/{self.alkisplugin_package}', self.alkisplugin_package)

        shutil.copy(f'{BASE_DIR}/docker/qgis-start.py', 'qgis-start.py')

        write_file(self.dockerfile_name, self.dockerfile())

    def dockerfile(self):
        apts = ' \\\n'.join(f"'{s}'" for s in self.apt_list)
        qt_select = 'ENV QT_SELECT=5' if self.qgis_major == '3' else ''

        fcgi_path_3 = 'usr/bin/qgis_mapserv.fcgi'
        fcgi_path_4 = 'usr/lib/cgi-bin/qgis_mapserv.fcgi'

        fcgi_copy = ''
        if os.path.isfile(f'{self.build_dir}/{self.qgis_package}/{fcgi_path_3}'):
            fcgi_copy = f'COPY {self.qgis_package}/{fcgi_path_3} /{fcgi_path_4}'
        elif os.path.isfile(f'{self.build_dir}/{self.qgis_package}/{fcgi_path_4}'):
            fcgi_copy = f'COPY {self.qgis_package}/{fcgi_path_4} /{fcgi_path_3}'
        else:
            sys.exit(f'qgis_mapserv.fcgi not found in {self.qgis_package}')

        df = f"""
            #
            # {self.image_full_name}
            # generated by gbd-qgis-server/docker/image-helper.py
            #
            FROM ubuntu:{self.ubuntu_version}
            LABEL Description="{self.image_description}" Vendor="{self.vendor}" Version="{self.version}"

            RUN apt-get update && apt-get install -y software-properties-common
            RUN apt-get update && DEBIAN_FRONTEND=noninteractive apt-get -y upgrade && DEBIAN_FRONTEND=noninteractive apt-get install -y {apts} && apt-get -y clean && apt-get -y purge --auto-remove

            COPY {self.qgis_package}/usr /usr
            {fcgi_copy}
            COPY {self.alkisplugin_package} /usr/share/{self.alkisplugin_package}
            COPY qgis-start.py /qgis-start.py

            RUN mkdir -p /qgis /vrun && chmod 1777 /qgis /vrun

            {qt_select}
            ENV LANG=C.UTF-8

            CMD ["python3", "/qgis-start.py"]
        """

        return '\n'.join(s.strip() for s in df.splitlines()) + '\n'


###


def run(cmd):
    print(f'> {cmd}', flush=True)
    res = subprocess.run(cmd, shell=True, check=False)
    if res.returncode:
        sys.exit(f'COMMAND FAILED, code {res.returncode}')


def lines(txt):
    ls = []
    for s in txt.strip().splitlines():
        s = s.strip()
        if s and not s.startswith('#'):
            ls.append(s)
    return ls


def read_file(path):
    with open(path, 'rt', encoding='utf8') as fp:
        return fp.read()


def write_file(path, text):
    with open(path, 'wt', encoding='utf8') as fp:
        fp.write(text)


def main():
    p = argparse.ArgumentParser(prog='image-helper.py', description='Docker builder for QGIS images.')
    p.add_argument('version', help='QGIS version like 3.44.15')
    p.add_argument('-arm', action='store_true', help='build for arm64 (default amd64)')
    p.add_argument('-debug', action='store_true', help='build the debug image')
    p.add_argument('-latest', action='store_true', help='tag the image with the major version (e.g. "3.44")')
    Builder(p.parse_args()).main()


if __name__ == '__main__':
    main()
